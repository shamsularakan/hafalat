/* ===== حساب الكميات (مشترك بين الخادم والواجهة) ===== */
export interface Headcount { men: number; women: number; seats_per_table: number }

export const guestTotal = (h: Headcount) => Math.max(0, h.men || 0) + Math.max(0, h.women || 0);

/** عدد الطاولات = عدد الضيوف ÷ الكراسي لكل طاولة، مقرّبًا لأعلى */
export const tableCount = (h: Headcount) => {
  const g = guestTotal(h);
  return g > 0 ? Math.ceil(g / Math.max(2, h.seats_per_table || 8)) : 0;
};

/** تقريب لأعلى بعد إزالة ضجيج الفاصلة العائمة (200 × 1.1 = 220.00000000000003 ← 220 لا 221) */
const ceil = (x: number) => Math.ceil(Math.round(x * 1e6) / 1e6);

export function autoQty(rule: { t: RuleType; v: number }, h: Headcount): number {
  const g = guestTotal(h), t = tableCount(h), v = Number(rule.v) || 0;
  switch (rule.t) {
    case "g": return ceil(g * v);
    case "w": return ceil(Math.max(0, h.women || 0) * v);
    case "m": return ceil(Math.max(0, h.men || 0) * v);
    case "t": return ceil(t * v);
    case "gd": return g > 0 && v > 0 ? Math.max(1, ceil(g / v)) : 0;
    default: return v;
  }
}

export function ruleLabel(rule: { t: RuleType; v: number }): string {
  switch (rule.t) {
    case "g": return `عدد الضيوف × ${rule.v}`;
    case "w": return `ضيوف النساء × ${rule.v}`;
    case "m": return `ضيوف الرجال × ${rule.v}`;
    case "t": return `عدد الطاولات × ${rule.v}`;
    case "gd": return `عدد الضيوف ÷ ${rule.v}`;
    default: return "كمية ثابتة";
  }
}

